export const getCurrentChapter = (frame: number, fps: number = 60): ChapterInfo => {
  const currentSec = frame / fps;
  for (const ch of chapters) {
    if (currentSec >= ch.startSec && currentSec < ch.endSec) {
      return ch;
    }
  }
  return chapters[chapters.length - 1];
};
